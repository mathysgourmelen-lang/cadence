// Launches the real built app with seeded data and screenshots every screen.
const { _electron: electron } = require('playwright')
const path = require('path')
const out = process.argv[2]
const videos = process.argv[3]
const theme = process.argv[4] || 'dark'
;(async () => {
  const app = await electron.launch({
    executablePath: require('electron'),
    args: [path.join(__dirname, '..'), '--no-sandbox', '--force-device-scale-factor=2'],
    env: { ...process.env, CADENCE_SKIP_ACCOUNT_CHECK: '1' }
  })
  const errors = []
  const win = await app.firstWindow()
  win.on('console', (m) => (m.type() === 'error' || m.type() === 'warning') && errors.push(`[${m.type()}] ${m.text()}`))
  win.on('pageerror', (e) => errors.push(`[pageerror] ${e.message}`))
  await app.evaluate(({ BrowserWindow }) => {
    const w = BrowserWindow.getAllWindows()[0]
    w.setSize(1440, 900)
    w.show()
  })
  await win.waitForSelector('.sidebar')
  await win.evaluate((t) => window.cadence.updateSettings({ appearance: t }), theme)
  await win.waitForTimeout(600)
  const shot = async (name) => {
    await win.waitForTimeout(700)
    await win.screenshot({ path: path.join(out, `${theme}-${name}.png`) })
  }
  const nav = async (label) => {
    await win.click(`.nav-item:has-text("${label}")`)
    await win.waitForTimeout(300)
  }
  await nav('Library')
  await win.waitForSelector('.lib-card')
  await win.waitForTimeout(3500)
  await shot('library')
  for (let i = 0; i < 3; i++) await win.keyboard.press('Control+-')
  await win.waitForTimeout(1500)
  await shot('library-dense')
  await win.keyboard.press('Control+0')
  await win.hover('.lib-card:nth-child(2)')
  await win.waitForTimeout(1500)
  await win.click('.lib-card:nth-child(3)')
  await win.click('.lib-card:nth-child(4)')
  await shot('library-select')
  await win.click('.select-bar .btn.ghost')
  await nav('Views')
  await win.waitForTimeout(800)
  await shot('views')
  await win.hover('.spark svg >> nth=0', { position: { x: 200, y: 30 } })
  await shot('views-hover')
  await win.locator('.page').evaluate((el) => el.scrollTo(0, 2000))
  await shot('views-scrolled')
  // Retention needs the real YouTube API: stub it with a realistic curve.
  await app.evaluate(({ ipcMain }) => {
    ipcMain.removeHandler('analytics:retention')
    ipcMain.handle('analytics:retention', () => ({
      ok: true,
      value: Array.from({ length: 100 }, (_, i) => {
        const at = (i + 1) / 100
        return { at, watch: Math.max(0.28, 1.08 * Math.exp(-at * 1.1) - (i < 4 ? 0.06 * (4 - i) : 0) + (i > 88 ? 0.08 : 0)), relative: 0.63 }
      })
    }))
  })
  await nav('Analytics')
  await win.waitForTimeout(1200)
  await shot('analytics-ig')
  await win.click('.acct-switch .acct-chip:nth-child(2)')
  await win.waitForTimeout(600)
  await shot('analytics-ig-second')
  await win.click('.acct-switch .acct-chip:nth-child(1)')
  await win.click('.an-table tbody tr:nth-child(1)')
  await win.waitForTimeout(800)
  await shot('analytics-ig-detail')
  await win.keyboard.press('Escape')
  await win.click('.segmented button:has-text("YouTube")')
  await win.waitForTimeout(1000)
  await shot('analytics-yt')
  await win.click('.an-table tbody tr:nth-child(1)')
  await win.waitForSelector('.ret-chart svg')
  await win.hover('.ret-chart svg', { position: { x: 220, y: 90 } })
  await win.waitForTimeout(500)
  await shot('analytics-yt-retention')
  await win.keyboard.press('Escape')
  await nav('Queue')
  await shot('queue')
  await nav('Calendar')
  await shot('calendar')
  await nav('History')
  await shot('history')
  await nav('Accounts')
  await shot('accounts')
  await nav('Settings')
  await shot('settings')
  await nav('Setup Guide')
  await shot('guide')
  await nav('Compose')
  await shot('compose-empty')
  // Stub the file dialog and import real files through the app.
  const files = ['morning-routine.mp4', 'tokyo.mp4', 'landscape-vlog.mp4'].map((f) => path.join(videos, f))
  await app.evaluate(({ dialog }, paths) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: paths })
  }, files)
  await win.click('button:has-text("Choose videos")')
  await win.waitForSelector('.tray-item')
  await win.fill('textarea[placeholder^="Write a caption"]', 'My 5am routine that actually stuck ☀️ Save this for tomorrow.\n\n#morningroutine #productivity @max.creates')
  await win.waitForTimeout(2500)
  await shot('compose')
  await win.click('.acct-picker .acct-chip:has-text("max.cooks")')
  await win.waitForTimeout(300)
  await shot('compose-accounts')
  await win.click('.acct-picker .acct-chip:has-text("max.cooks")')
  await win.click('.chip:has-text("Core tags")')
  await win.locator('.page').evaluate((el) => el.scrollTo(0, 400))
  await shot('compose-scrolled')
  await app.evaluate(({ dialog }, p) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [p] })
  }, path.join(videos, 'cover.png'))
  await win.click('button:has-text("Choose image")')
  await win.waitForSelector('.yt-thumb-box img')
  await win.locator('.yt-thumb-field').scrollIntoViewIfNeeded()
  await shot('compose-yt-thumbnail')
  await app.evaluate(({ dialog }, paths) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: paths })
  }, files)
  await win.click('.tray-item:nth-child(3)')
  await shot('compose-landscape')
  await win.click('button:has-text("Spread schedule")')
  await shot('spread')
  await win.click('.modal button:has-text("Apply")')
  await win.click('.tray-item:nth-child(2)')
  await win.fill('textarea[placeholder^="Write a caption"]', 'Golden hour in Shibuya 🌆 #tokyo #travel')
  await win.click('.tray-item:nth-child(3)')
  await win.fill('textarea[placeholder^="Write a caption"]', 'Weekend vlog, full version on the channel')
  await win.click('button:has-text("Schedule all")')
  await win.waitForTimeout(800)
  await shot('after-schedule')
  await nav('Queue')
  await shot('queue-after')
  // Library → Create posts hands the selected files to Compose.
  await nav('Library')
  await win.waitForSelector('.lib-card')
  await win.click('.lib-card:nth-child(1)')
  await win.click('.lib-card:nth-child(2)', { modifiers: ['Shift'] })
  await win.click('.select-bar .btn.primary')
  await win.waitForSelector('.tray-item')
  await win.waitForTimeout(1500)
  await shot('library-to-compose')
  const state = await win.evaluate(() => window.cadence.getState())
  console.log('posts:', state.posts.length, state.posts.map((p) => `${p.video.fileName}:${p.instagram.state}/${p.youtube.state}`).join(', '))
  console.log('ERRORS:\n' + errors.join('\n'))
  await app.evaluate(({ app }) => app.exit(0))
})().catch((e) => {
  console.error(e)
  process.exit(1)
})
